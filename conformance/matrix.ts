// Builds conformance/MATRIX.md: each normative rule of the specification, the reference tests that exercise it,
// the validator checks that test it against any implementation, and what only a person can check.
// Fails if a cited test does not exist. Usage, from the repository root: node conformance/matrix.ts

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RAIZ = join(import.meta.dirname, "..");
const spec = readFileSync(join(RAIZ, "spec", "spec.tpl.html"), "utf8");
const matriz = JSON.parse(readFileSync(join(import.meta.dirname, "matrix.json"), "utf8")).rules as Record<string, { tests: string[]; manual?: string; external?: string }>;
const validador = readFileSync(join(import.meta.dirname, "validate.ts"), "utf8");

// Normative requirements carry an identifier (I1…, ID1…, E1…, P1…, R1…, O1…).
const reqs = [...spec.matchAll(/<div class="req" id="([a-z]+\d+)">/g)].map((m) => m[1]);
// Validator checks and the rules each cites: check("D1", ["native-discovery"], …) or ok(cond, "D1", [...], …)
const checks: { id: string; rules: string[] }[] = [];
for (const m of validador.matchAll(/(?:check|ok)\((?:[^,]+,\s*)?"([A-Z]\d+|[A-Z]\d+[a-z]?)",\s*\[([^\]]*)\]/g)) checks.push({ id: m[1], rules: [...m[2].matchAll(/"([^"]+)"/g)].map((x) => x[1].toLowerCase()) });
// Every test title of the reference suite, with its file.
const titulos: { file: string; title: string }[] = [];
for (const f of readdirSync(join(RAIZ, "reference", "test")).filter((x) => x.endsWith(".test.ts")))
	for (const m of readFileSync(join(RAIZ, "reference", "test", f), "utf8").matchAll(/^test\("((?:[^"\\]|\\.)*)"/gm)) titulos.push({ file: `reference/test/${f}`, title: m[1] });

const faltan: string[] = [];
const filas: string[] = [];
const claves = [...new Set([...reqs, ...Object.keys(matriz)])];
for (const k of claves) {
	const e = matriz[k];
	const tests = (e?.tests ?? []).map((p) => {
		const t = titulos.find((x) => x.title.startsWith(p));
		if (!t) faltan.push(`${k}: no test starts with «${p}»`);
		return t ? `${t.file.replace("reference/test/", "")} · «${p}»` : `MISSING «${p}»`;
	});
	const vc = [...new Set(checks.filter((c) => c.rules.includes(k)).map((c) => c.id))];
	const etiqueta = /^[a-z]+\d+$/.test(k) ? k.toUpperCase() : k;
	const cubierta = tests.length || vc.length || e?.external;
	filas.push(`| [${etiqueta}](https://vxpprotocol.org/spec/#${k}) | ${tests.join("<br>") || "—"} | ${vc.join(", ") || "—"} | ${[e?.external, e?.manual ? `manual: ${e.manual}` : ""].filter(Boolean).join("<br>") || "—"} | ${cubierta ? "" : "**not covered**"} |`);
}
const sinCobertura = filas.filter((f) => f.includes("**not covered**")).length;
const md = [
	"# VXP conformance matrix",
	"",
	"Generated by `node conformance/matrix.ts` from the specification (`spec/spec.tpl.html`), `conformance/matrix.json`, the reference tests (`reference/test/`) and the validator (`conformance/validate.ts`). Do not edit by hand.",
	"",
	"- **Reference tests** run in process against the reference implementation (`cd reference && npm test`).",
	"- **Validator checks** run against any implementation of the native profile (`node conformance/validate.ts <config>`); their ids are in the validator's report.",
	"- **Other** lists official tools of other protocols, vectors, and what only a person can check (see `CHECKLIST.md`).",
	"",
	`Rules: ${claves.length} · without any coverage: ${sinCobertura}`,
	"",
	"| Rule | Reference tests | Validator checks | Other | |",
	"|---|---|---|---|---|",
	...filas,
	"",
].join("\n");
writeFileSync(join(import.meta.dirname, "MATRIX.md"), md);
console.log(`MATRIX.md: ${claves.length} rules, ${new Set(checks.map((c) => c.id)).size} validator checks, ${titulos.length} reference tests, ${sinCobertura} rules without coverage`);
if (faltan.length) {
	console.error(faltan.join("\n"));
	process.exit(1);
}
